/** Код языка платформы/браузера → поддерживаемый язык. */
export function detectLang(sdkLang?: string | null): Lang {
  const raw = (sdkLang || navigator.language || 'ru').slice(0, 2).toLowerCase();
  return raw === 'en' ? 'en' : raw === 'tr' ? 'tr' : 'ru';
}

