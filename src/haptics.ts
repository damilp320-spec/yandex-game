// Тактильный отклик. В мобильных казуалках половина «сочности» действия — это
// короткая вибрация, а не звук: она работает и с выключенным звуком (а звук на
// Яндекс Играх многие выключают сразу). Длительности намеренно очень короткие —
// длинная вибрация раздражает и жрёт батарею.
import { S } from './state';

export const BUZZ = { merge: 15, win: 30, golden: 10, claim: 20, fail: 25 };

export function buzz(ms: number): void {
  if (!S.hapticsOn) return;
  try { navigator.vibrate?.(ms); } catch { /* устройство без вибромотора */ }
}
